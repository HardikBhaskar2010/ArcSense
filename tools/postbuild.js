import fs from 'fs';
import path from 'path';
import { execSync } from 'child_process';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const distHtml = path.join(root, 'dist', 'index.html');
const dashHtml = path.join(root, 'dashboard', 'index.html');

if (fs.existsSync(distHtml)) {
  fs.copyFileSync(distHtml, dashHtml);
  console.log(`[postbuild] Copied ${distHtml} -> ${dashHtml}`);
  try {
    execSync('python tools/embed_dashboard.py', { cwd: root, stdio: 'inherit' });
  } catch (err) {
    console.warn('[postbuild] Python execution failed, updating dashboard_html.h directly in Node...');
    const html = fs.readFileSync(dashHtml, 'utf-8');
    const headerPath = path.join(root, 'firmware', 'arcsense', 'dashboard_html.h');
    const content = `// AUTO-GENERATED by tools/postbuild.js - do not edit by hand.\n#pragma once\n#include <pgmspace.h>\nconst char DASH_HTML[] PROGMEM = R"rawliteral(${html})rawliteral";\n`;
    fs.writeFileSync(headerPath, content, 'utf-8');
    console.log(`[postbuild] Wrote ${headerPath} (${html.length} bytes)`);
  }
} else {
  console.error(`[postbuild] Error: ${distHtml} does not exist`);
  process.exit(1);
}
